"""Write userland/libsandbox/sbpl_consts.h: the constant names SBPL filters take
(SYS_open, AF_UNIX, F_GETFL, SIOCGIFMTU, SIGKILL, PRIV_..., MSC_...) and their values.

    tools/sandbox/gen-consts.py

Values come from the macOS SDK's headers (compiled and printed by a probe
program) and, for the kernel-only PRIV_* and mach trap names, from the XNU
source under build/xnu-work (tools/build-kernel.sh fetches it).
"""
import re
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SDK = Path(subprocess.run(['xcrun', '--show-sdk-path'], check=True, capture_output=True,
                          text=True).stdout.strip())
XNU = ROOT / 'build/xnu-work/xnu'

HEADERS = {
    'sys/fcntl.h': r'F_[A-Z0-9_]+',
    'sys/socket.h': r'(?:AF|PF|SOCK|SO|SOL|MSG)_[A-Z0-9_]+',
    'netinet/in.h': r'IPPROTO_[A-Z0-9_]+',
    'sys/signal.h': r'SIG[A-Z0-9]+',
    'sys/sockio.h': r'SIOC[A-Z0-9_]+',
    'sys/errno.h': r'E[A-Z0-9]+',
    'sys/ttycom.h': r'TIOC[A-Z0-9_]+',
    'sys/filio.h': r'FIO[A-Z0-9_]+',
    'sys/kern_control.h': r'CTLIOC[A-Z0-9_]+',
    'sys/disk.h': r'DKIOC[A-Z0-9_]+',
}

values = {}
for line in (SDK / 'usr/include/sys/syscall.h').read_text().splitlines():
    m = re.match(r'#define\s+(SYS_\w+)\s+(\d+)\s*$', line)
    if m:
        values[m.group(1)] = int(m.group(2))

names = set()
for header, pattern in HEADERS.items():
    text = (SDK / 'usr/include' / header).read_text(errors='replace')
    for m in re.finditer(r'#\s*define\s+(' + pattern + r')\b(?!\()', text):
        names.add(m.group(1))
includes = ''.join(f'#include <{h}>\n' for h in ['sys/types.h', 'sys/ioctl.h', 'termios.h', 'sys/socket.h', 'net/if.h', 'net/if_media.h', *HEADERS])
probe = includes + '#include <stdio.h>\nint main(void) {\n'
for n in sorted(names):
    probe += f'#ifdef {n}\n printf("{n} %lld\\n", (long long)({n}));\n#endif\n'
probe += ' return 0;\n}\n'
with tempfile.TemporaryDirectory() as tmp:
    src, exe = Path(tmp) / 'probe.c', Path(tmp) / 'probe'
    src.write_text(probe)
    subprocess.run(['xcrun', 'clang', '-w', '-o', str(exe), str(src)], check=True)
    for line in subprocess.run([str(exe)], check=True, capture_output=True, text=True).stdout.splitlines():
        n, v = line.split()
        values.setdefault(n, int(v))

priv = XNU / 'bsd/sys/priv.h'
for line in priv.read_text().splitlines():
    m = re.match(r'#define\s+(PRIV_\w+)\s+(\d+)\b', line)
    if m:
        values[m.group(1)] = int(m.group(2))
traps = (XNU / 'osfmk/kern/syscall_sw.c').read_text()
table = traps[traps.index('mach_syscall_name_table'):]
for m in re.finditer(r'/\*\s*(\d+)\s*\*/\s*"(\w+)"', table):
    if m.group(2) != 'kern_invalid':
        values.setdefault('MSC_' + m.group(2), int(m.group(1)))

out = ['/* SPDX-License-Identifier: MIT OR Apache-2.0 */',
       '/* Constant names SBPL filters take, and their values.',
       "   Generated by tools/sandbox/gen-consts.py; don't edit by hand. */",
       '#ifndef SBPL_CONSTS_H', '#define SBPL_CONSTS_H', '', '#include <stdlib.h>',
       '#include <string.h>', '', 'static const struct { const char *name; long long value; } sbpl_constants[] = {']
out += [f'\t{{ "{n}", {v}LL }},' for n, v in sorted(values.items())]
out += ['};', '', 'static int', 'sbpl_constant_cmp(const void *key, const void *entry)', '{',
        '\treturn strcmp(key, *(const char *const *)entry);', '}', '',
        '/* 1 and *value for a known name, 0 otherwise. */', 'static int',
        'sbpl_constant(const char *name, long long *value)', '{',
        '\tconst void *hit = bsearch(name, sbpl_constants, sizeof(sbpl_constants) / sizeof(sbpl_constants[0]),',
        '\t    sizeof(sbpl_constants[0]), sbpl_constant_cmp);', '\tif (!hit) {', '\t\treturn 0;', '\t}',
        '\t*value = ((const typeof(sbpl_constants[0]) *)hit)->value;', '\treturn 1;', '}', '',
        '#endif /* SBPL_CONSTS_H */', '']
(ROOT / 'userland/libsandbox/sbpl_consts.h').write_text('\n'.join(out))
print(f'{len(values)} constants')
