def c_inventory(framework: str) -> set[str]:
    module_path = ROOT / "tools" / "c-api-audit.py"
    spec = importlib.util.spec_from_file_location("finch_c_api_audit", module_path)
    if not spec or not spec.loader:
        raise RuntimeError("could not load the SDK C API scanner")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    symbols = {symbol[1:] if symbol.startswith("_") else symbol for symbol in module.sdk_declarations(framework)}
    sdk = Path(subprocess.run(["xcrun", "--sdk", "macosx", "--show-sdk-path"], check=True,
                              capture_output=True, text=True).stdout.strip())
    headers = sdk / "System/Library/Frameworks" / f"{framework}.framework/Headers"
    inline = re.compile(r"\b(?:CF_INLINE|NS_INLINE)\s+[^;{}]*?\b([A-Za-z_][A-Za-z0-9_]*)\s*\(")
    for header in headers.rglob("*.h"):
        text = header.read_text(errors="replace")
        text = re.sub(r"/\*.*?\*/|//[^\n]*", "", text, flags=re.S)
        symbols.update(inline.findall(text))
    return symbols


def objc_inventory(framework: str) -> set[str]:
    scanner = ROOT / "tools" / "api-audit" / "headers.py"
    result = subprocess.run([sys.executable, str(scanner), framework], check=True, capture_output=True, text=True)
    return {line.strip() for line in result.stdout.splitlines() if line.strip()}


def swift_inventory(framework: str) -> set[str]:
    """Collect public Swift member spellings from the SDK's macOS interface."""
    sdk = Path(subprocess.run(["xcrun", "--sdk", "macosx", "--show-sdk-path"], check=True,
                              capture_output=True, text=True).stdout.strip())
    path = sdk / "System/Library/Frameworks" / f"{framework}.framework/Versions/C/Modules" / f"{framework}.swiftmodule/arm64e-apple-macos.swiftinterface"
    if not path.exists():
        return set()
    output: set[str] = set()
    scope: list[tuple[int, str]] = []
    for line in path.read_text(errors="replace").splitlines():
        stripped = line.strip()
        indent = len(line) - len(line.lstrip())
        while scope and indent <= scope[-1][0] and stripped:
            scope.pop()
        decl = re.match(r"(?:public|open)\s+(?:(?:final|nonisolated|override|static|class|mutating|consuming|borrowing)\s+)*(func|var|let|subscript)\s+([^ (:{]+)", stripped)
        if decl and scope:
            typ = scope[-1][1]
            output.add(f"{framework}.{typ}.{decl.group(2)}")
        typ = re.match(r"(?:public|open)\s+(?:struct|enum|class|actor|protocol)\s+([A-Za-z_][A-Za-z0-9_]*)", stripped)
        if typ and "{" in stripped:
            scope.append((indent, typ.group(1)))
        elif stripped.startswith("extension ") and "{" in stripped:
            match = re.match(r"extension\s+(?:Foundation\.)?([A-Za-z_][A-Za-z0-9_]*)", stripped)
            if match:
                scope.append((indent, match.group(1)))
    return output


def generate(framework: str, output_dir: Path) -> dict:
    output_dir.mkdir(parents=True, exist_ok=True)
    if framework == "CoreFoundation":
        tested = CF_CASES
        source = CF_SOURCE
        filename = "CoreFoundation.m"
    elif framework == "Foundation":
        tested = FOUNDATION_CASES
        source = FOUNDATION_SOURCE
        filename = "Foundation.m"
    else:
        raise ValueError(f"unsupported framework: {framework}")

    c_items = c_inventory(framework)
    objc_items = objc_inventory(framework)
    swift_items = swift_inventory(framework)
    declared = c_items | objc_items | swift_items
    missing = [name for name, _ in tested if name not in declared]
    if missing:
        raise RuntimeError(f"catalog APIs are not in the {framework} SDK inventory: {', '.join(missing)}")

    source_path = output_dir / filename
    source_path.write_text(source)
    return {
        "framework": framework,
        "sdk_items": sorted(declared),
        "tested_items": [{"name": name, "category": category} for name, category in tested],
        "source": str(source_path),
        "input_count": len(STRINGS),
        "seed": "0xF1AC2026",
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("framework", choices=("CoreFoundation", "Foundation"))
    parser.add_argument("--output-dir", type=Path, default=BUILD)
    args = parser.parse_args()
    try:
        info = generate(args.framework, args.output_dir)
    except (OSError, RuntimeError, subprocess.CalledProcessError) as error:
        print(f"difftest generation failed: {error}", file=sys.stderr)
        return 2
    print(json.dumps({key: value for key, value in info.items() if key != "sdk_items"}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
