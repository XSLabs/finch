"""Generate typed CoreFoundation and Foundation comparison programs.

The SDK headers are the inventory.  The small catalogue below supplies safe,
typed input builders for APIs whose behaviour depends on their arguments.  A
single generated executable dispatches one API item per process so a crash is
kept with the item that caused it.
"""
