def swift_inventory(framework: str) -> set[str]:
    """Collect public Swift member spellings from the SDK's macOS interface."""
    sdk = Path(subprocess.run(["xcrun", "--sdk", "macosx", "--show-sdk-path"], check=True,
                              capture_output=True, text=True).stdout.strip())
    path = sdk / "System/Library/Frameworks" / f"{framework}.framework/Versions/C/Modules" / f"{framework}.swiftmodule/arm64e-apple-macos.swiftinterface"
    if not path.exists():
        return set()
    output: set[str] = set()
    scope: list[tuple[int, str]] = []
    for line in path.read_text(errors="replace").splitlines():
        stripped = line.strip()
        indent = len(line) - len(line.lstrip())
        while scope and indent <= scope[-1][0] and stripped:
            scope.pop()
        decl = re.match(r"(?:public|open)\s+(?:(?:final|nonisolated|override|static|class|mutating|consuming|borrowing)\s+)*(func|var|let|subscript)\s+([^ (:{]+)", stripped)
        if decl and scope:
            typ = scope[-1][1]
            output.add(f"{framework}.{typ}.{decl.group(2)}")
        typ = re.match(r"(?:public|open)\s+(?:struct|enum|class|actor|protocol)\s+([A-Za-z_][A-Za-z0-9_]*)", stripped)
        if typ and "{" in stripped:
            scope.append((indent, typ.group(1)))
        elif stripped.startswith("extension ") and "{" in stripped:
            match = re.match(r"extension\s+(?:Foundation\.)?([A-Za-z_][A-Za-z0-9_]*)", stripped)
            if match:
                scope.append((indent, match.group(1)))
    return output


def generate(framework: str, output_dir: Path) -> dict:
    output_dir.mkdir(parents=True, exist_ok=True)
    manual_metadata = {}
    if framework in GRAPHICS_CASES:
        cases = GRAPHICS_CASES[framework]
        tested = [(name, category) for name, category, _comparison in cases]
        manual_metadata = {name: comparison for name, _category, comparison in cases if comparison}
        source = GRAPHICS_SOURCE.replace("/* MANUAL_C_SOURCE */", GRAPHICS_MANUAL_SOURCE[framework])
        source = source.replace("/* STRING_TABLE */", string_table())
        manual_entries = []
        for name, _category in tested:
            function_name = re.sub(r"\W+", "_", name)
            manual_entries.append(f'    {{ "{name}", test_{function_name} }},')
        source = source.replace("/* MANUAL_C_ENTRIES */", "\n".join(manual_entries))
        defines = ["#define FINCH_DIFFTEST_GRAPHICS 1"]
        if framework == "CoreText":
            defines.append("#define FINCH_DIFFTEST_CORETEXT 1")
        if framework == "ImageIO":
            defines.append("#define FINCH_DIFFTEST_IMAGEIO 1")
        source = source.replace("/* FRAMEWORK_DEFINES */", "\n".join(defines))
        filename = f"{framework}.m"
    elif framework == "CoreFoundation":
        tested = CF_CASES
        source = CF_SOURCE
        filename = "CoreFoundation.m"
    elif framework == "Foundation":
        tested = FOUNDATION_CASES
        source = FOUNDATION_SOURCE
        filename = "Foundation.m"
    elif framework == "AppKit":
        tested = []
        source = APPKIT_SOURCE
        filename = "AppKit.m"
    else:
        raise ValueError(f"unsupported framework: {framework}")

    details = c_declaration_details(framework)
    c_items = c_inventory(framework, details)
    objc_items = objc_inventory(framework)
    swift_items = swift_inventory(framework)
    declared = c_items | objc_items | swift_items
    missing = [name for name, _ in tested if name not in declared]
    if missing:
        raise RuntimeError(f"catalog APIs are not in the {framework} SDK inventory: {', '.join(missing)}")

    manual_names = {name for name, _ in tested}
    finch_symbols = c_export_inventory(framework)
    typed = _TYPED.prepare(framework, c_items, objc_items, swift_items, details, manual_names,
                           finch_symbols, output_dir)
    source = source.replace("/* TYPED_C_SOURCE */", typed["c_source"])
    source = source.replace("/* TYPED_C_ENTRIES */", typed["c_entries"])
    source = source.replace("/* TYPED_OBJC_RUNTIME */", typed["objc_runtime"] if framework in {"Foundation", "AppKit"} else "")

    generated_items = typed["auto_c_items"] + typed["auto_objc_items"]
    tested = list(tested) + [(item["name"], item["category"]) for item in generated_items]
    exercised_names = {name for name, _ in tested}
    unexercised = {name: typed["skipped"].get(name, "no safe type-driven input could be built")
                   for name in sorted(declared - exercised_names)}

    source_path = output_dir / filename
    source_path.write_text(source)
    tested_item_records = []
    for name, category in tested:
        entry = {"name": name, "category": category}
        if name in manual_metadata:
            entry["comparison"] = manual_metadata[name]
        tested_item_records.append(entry)
    return {
        "framework": framework,
        "sdk_items": sorted(declared),
        "tested_items": tested_item_records,
        "unexercised_items": unexercised,
        "type_metadata": typed["metadata"],
        "source": str(source_path),
        "input_count": len(STRINGS),
        "seed": "0xF1AC2026",
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("framework", choices=("CoreFoundation", "Foundation", "CoreGraphics", "CoreText", "ImageIO", "AppKit"))
    parser.add_argument("--output-dir", type=Path, default=BUILD)
    args = parser.parse_args()
    try:
        info = generate(args.framework, args.output_dir)
    except (OSError, RuntimeError, subprocess.CalledProcessError) as error:
        print(f"difftest generation failed: {error}", file=sys.stderr)
        return 2
    print(json.dumps({key: value for key, value in info.items() if key != "sdk_items"}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
