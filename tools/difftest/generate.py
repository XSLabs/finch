WORDS = [
    "", "a", "A", "abc", "ABC", "Straße", "STRASSE", "café", "cafe\u0301",
    "Ångström", "e\u0301", "é", "İstanbul", "東京", "עברית", "العربية",
    "👩🏽\u200d💻", "👨‍👩‍👧‍👦", "🇨🇦", "a\u00a0b", "file2", "file10",
    "https://example.test/a%20b?q=1#part", "a,b,,c", "line one\nline two",
]
RANDOM_PARTS = ["a", "B", "é", "e\u0301", "ß", "Ω", "字", "🙂", "العربية", "7", " ", "-"]


def inputs() -> list[str]:
    rng = random.Random(0xF1AC_2026)
    result = list(WORDS)
    for _ in range(18):
        result.append("".join(rng.choice(RANDOM_PARTS) for _ in range(rng.randint(1, 8))))
    result.append("x" * 65536)
    return result


STRINGS = inputs()


def c_string(value: str) -> str:
    """Encode UTF-8 with fixed-width octal escapes safe next to hex digits."""
    raw = value.encode("utf-8")
    return '"' + "".join(chr(b) if 0x20 <= b < 0x7f and b not in (34, 92)
                         else (r'\"' if b == 34 else r"\\" if b == 92
                               else r"\n" if b == 10 else r"\r" if b == 13
                               else r"\t" if b == 9 else f"\{b:03o}")
                         for b in raw) + '"'


def string_table() -> str:
    return "static const char *const samples[] = {\n" + "\n".join(
        f"    {c_string(value)}," for value in STRINGS
    ) + "\n};\n#define SAMPLE_COUNT (sizeof(samples) / sizeof(samples[0]))\n"


