def c_string(value: str) -> str:
    """Encode UTF-8 with fixed-width octal escapes safe next to hex digits."""
    raw = value.encode("utf-8")
    return '"' + "".join(chr(b) if 0x20 <= b < 0x7f and b not in (34, 92)
                         else (r'\"' if b == 34 else r"\\" if b == 92
                               else r"\n" if b == 10 else r"\r" if b == 13
                               else r"\t" if b == 9 else f"\{b:03o}")
                         for b in raw) + '"'


