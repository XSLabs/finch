"""Writes rules.h: the Gauss-Kronrod rules (Gauss n, Kronrod 2n+1 points, for n = 7, 10,
15, 20, 25, 30) and the Gauss-Kronrod-Patterson sequence 10, 21, 43, 87 that quadrature.c
integrates with, computed here at high precision with mpmath.

Kronrod's extension of an n-point Gauss rule adds the n+1 zeros of the Stieltjes
polynomial E, which is orthogonal on [-1, 1] to x^k P_n(x) for k < n+1; Patterson's
extension of a rule with nodes Q adds the zeros of the polynomial orthogonal to x^k Q(x).
Weights then solve the moment equations. Only the non-negative nodes are written (the
rules are symmetric)."""
import mpmath as mp

mp.mp.dps = 120


def legendre_coeffs(n):
    """Legendre P_n as coefficients, lowest degree first"""
    p0, p1 = [mp.mpf(1)], [mp.mpf(0), mp.mpf(1)]
    if n == 0:
        return p0
    for k in range(1, n):
        # (k+1) P_{k+1} = (2k+1) x P_k - k P_{k-1}
        xp = [mp.mpf(0)] + p1
        nxt = [((2 * k + 1) * (xp[i] if i < len(xp) else 0) - k * (p0[i] if i < len(p0) else 0)) / (k + 1)
               for i in range(len(xp))]
        p0, p1 = p1, nxt
    return p1


def poly_mul(a, b):
    out = [mp.mpf(0)] * (len(a) + len(b) - 1)
    for i, x in enumerate(a):
        for j, y in enumerate(b):
            out[i + j] += x * y
    return out


def integral_x(k):
    """the integral of x^k over [-1, 1]"""
    return mp.mpf(0) if k % 2 else mp.mpf(2) / (k + 1)


def extension(base, degree):
    """the monic polynomial of the given degree orthogonal to x^k base(x), k < degree,
    keeping parity (degree's parity)"""
    # unknown coefficients c_0..c_{degree-1}, monic: x^degree + sum c_i x^i
    rows, rhs = [], []
    for k in range(degree):
        w = [mp.mpf(0)] * (k) + [mp.mpf(1)]  # x^k
        bw = poly_mul(base, w)
        row = []
        for i in range(degree):
            row.append(sum(c * integral_x(j + i) for j, c in enumerate(bw)))
        rows.append(row)
        rhs.append(-sum(c * integral_x(j + degree) for j, c in enumerate(bw)))
    sol = mp.lu_solve(mp.matrix(rows), mp.matrix(rhs))
    return [sol[i] for i in range(degree)] + [mp.mpf(1)]


def roots(coeffs):
    r = mp.polyroots(list(reversed(coeffs)), maxsteps=400, extraprec=600)
    return sorted(mp.re(x) for x in r)


def weights(nodes):
    """weights integrating x^k exactly for k < len(nodes)"""
    n = len(nodes)
    A = mp.matrix([[x ** k for x in nodes] for k in range(n)])
    b = mp.matrix([integral_x(k) for k in range(n)])
    w = mp.lu_solve(A, b)
    return [w[i] for i in range(n)]


def half(nodes, ws):
    """the non-negative nodes, largest first, with their weights"""
    pairs = sorted(((x, w) for x, w in zip(nodes, ws) if x >= -mp.mpf(10) ** -60), key=lambda p: -p[0])
    return [p[0] if p[0] > 0 else mp.mpf(0) for p in pairs], [p[1] for p in pairs]


def fmt(v):
    return mp.nstr(v, 25, min_fixed=-30, max_fixed=30)


out = ['/* SPDX-License-Identifier: MIT OR Apache-2.0 */',
       '/* Generated by gen-rules.py: Gauss-Kronrod and Gauss-Kronrod-Patterson rules on [-1, 1],',
       '   non-negative nodes only, largest first. Do not edit. */', '']

for n in (7, 10, 15, 20, 25, 30):
    P = legendre_coeffs(n)
    gauss = roots(P)
    E = extension(P, n + 1)
    kron = sorted(gauss + roots(E))
    wk = weights(kron)
    wg = weights(gauss)
    xk, wk = half(kron, wk)
    xg, wg = half(gauss, wg)
    m = 2 * n + 1
    out.append(f'/* {n}-point Gauss, {m}-point Kronrod: xgk[i] (the Gauss nodes are xgk[1], xgk[3], ...) */')
    out.append(f'static const double xgk{m}[{len(xk)}] = {{' + ', '.join(fmt(x) for x in xk) + '};')
    out.append(f'static const double wgk{m}[{len(wk)}] = {{' + ', '.join(fmt(x) for x in wk) + '};')
    out.append(f'static const double wg{m}[{len(wg)}] = {{' + ', '.join(fmt(x) for x in wg) + '};')
    out.append('')

# Patterson: 10 Gauss -> 21 -> 43 -> 87, each rule's weights over all its nodes
P10 = legendre_coeffs(10)
nodes = roots(P10)
base = P10
for count in (21, 43, 87):
    added = count - len(nodes)
    ext = extension(base, added)
    new = roots(ext)
    nodes = sorted(nodes + new)
    ws = weights(nodes)
    xs, wss = half(nodes, ws)
    out.append(f'/* the {count}-point Patterson rule */')
    out.append(f'static const double xp{count}[{len(xs)}] = {{' + ', '.join(fmt(x) for x in xs) + '};')
    out.append(f'static const double wp{count}[{len(wss)}] = {{' + ', '.join(fmt(x) for x in wss) + '};')
    out.append('')
    base = poly_mul(base, ext)
g10 = roots(P10)
xg10, wg10 = half(g10, weights(g10))
out.append('/* the 10-point Gauss rule */')
out.append(f'static const double xg10[{len(xg10)}] = {{' + ', '.join(fmt(x) for x in xg10) + '};')
out.append(f'static const double wg10[{len(wg10)}] = {{' + ', '.join(fmt(x) for x in wg10) + '};')
print('\n'.join(out))
