static int
sbpl_constant_cmp(const void *key, const void *entry)
{
	return strcmp(key, *(const char *const *)entry);
}

/* 1 and *value for a known name, 0 otherwise. */
static int
sbpl_constant(const char *name, long long *value)
{
	const void *hit = bsearch(name, sbpl_constants, sizeof(sbpl_constants) / sizeof(sbpl_constants[0]),
	    sizeof(sbpl_constants[0]), sbpl_constant_cmp);
	if (!hit) {
		return 0;
	}
	*value = ((const typeof(sbpl_constants[0]) *)hit)->value;
	return 1;
}

